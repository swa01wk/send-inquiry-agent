"""Master data: the model, where it comes from, and a cached accessor.

The data itself is generated by `scripts/generate_master_data.py` into
`app/data/master_data.json` (docs/specs/l3-reliable-intake.md §3.8). Callers use
`load_master_data()`; which source backs it is set once by `configure_master_data`.
"""

from __future__ import annotations

import json
import logging
from collections.abc import Callable
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Literal, Protocol

from pydantic import BaseModel, Field

logger = logging.getLogger(__name__)


class MasterItem(BaseModel):
    id: str
    label: str
    label_ar: str | None = None


class UnitType(MasterItem):
    code: str


class Region(MasterItem):
    pass


class City(MasterItem):
    region: str | None = None


class Mall(BaseModel):
    id: str
    name: str
    name_ar: str | None = None
    city: str
    region: str | None = None
    aliases: list[str] = Field(default_factory=list)

    def names(self) -> list[str]:
        """Every name a user might write for this mall: English, Arabic, aliases."""
        candidates = [self.name, *([self.name_ar] if self.name_ar else []), *self.aliases]
        return list(dict.fromkeys(candidates))


class MasterData(BaseModel):
    regions: list[Region] = Field(default_factory=list)
    unit_types: list[UnitType] = Field(default_factory=list)
    sales_categories: list[MasterItem] = Field(default_factory=list)
    cities: list[City] = Field(default_factory=list)
    malls: list[Mall] = Field(default_factory=list)
    lease_periods: list[MasterItem] = Field(default_factory=list)
    rent_periods: list[MasterItem] = Field(default_factory=list)

    def label_for(self, kind: str, item_id: str) -> str | None:
        if kind not in {
            "unit_types",
            "sales_categories",
            "cities",
            "malls",
            "lease_periods",
            "rent_periods",
        }:
            raise KeyError(kind)
        if kind == "malls":
            for mall in self.malls:
                if mall.id == item_id:
                    return mall.name
        items = self._items_for_kind(kind)
        for item in items:
            if item.id == item_id:
                if isinstance(item, MasterItem):
                    return item.label
        return None

    def malls_in_city(self, city_id: str) -> list[Mall]:
        return [mall for mall in self.malls if mall.city == city_id]

    def region_for_mall(self, mall_id: str) -> str | None:
        for mall in self.malls:
            if mall.id == mall_id:
                return mall.region
        return None

    def unit_code(self, unit_type_id: str) -> str | None:
        for unit in self.unit_types:
            if unit.id == unit_type_id:
                return unit.code
        return None

    def mall_ids(self) -> set[str]:
        return {mall.id for mall in self.malls}

    def ids_for_kind(self, kind: str) -> set[str]:
        return {item.id for item in self._items_for_kind(kind)}

    def _items_for_kind(self, kind: str) -> list[MasterItem | Mall]:
        mapping: dict[str, list[MasterItem | Mall]] = {
            "unit_types": list(self.unit_types),
            "sales_categories": list(self.sales_categories),
            "cities": list(self.cities),
            "malls": list(self.malls),
            "lease_periods": list(self.lease_periods),
            "rent_periods": list(self.rent_periods),
        }
        if kind not in mapping:
            msg = f"Unknown master kind: {kind}"
            raise KeyError(msg)
        return mapping[kind]


# ---- Sources ------------------------------------------------------------------

SEED_DATA_PATH = Path(__file__).resolve().parent.parent / "data" / "master_data.json"


class MasterDataUnavailable(RuntimeError):
    """The source couldn't provide master data right now."""


class MasterDataSource(Protocol):
    name: str

    def fetch(self) -> MasterData: ...


class SeedMasterDataSource:
    """The generated JSON shipped with the app."""

    name = "seed"

    def __init__(self, path: Path = SEED_DATA_PATH) -> None:
        self._path = path

    def fetch(self) -> MasterData:
        raw = json.loads(self._path.read_text(encoding="utf-8"))
        return MasterData.model_validate(raw)


class CenomiMasterDataSource:
    """Cenomi's master data (malls, categories, Arabic names). Stub until access (L3 Q6)."""

    name = "cenomi"

    def fetch(self) -> MasterData:
        msg = "Cenomi master data isn't connected yet (L3 open question Q6)"
        raise MasterDataUnavailable(msg)


class CachedMasterData:
    """Serves one source, refreshed daily, falling back to the last good copy.

    If the very first fetch fails, `fallback` (normally the seed data) is used so the
    app can still start.
    """

    def __init__(
        self,
        source: MasterDataSource,
        *,
        fallback: MasterDataSource | None = None,
        refresh_every: timedelta = timedelta(days=1),
        clock: Callable[[], datetime] = lambda: datetime.now(UTC),
    ) -> None:
        self.source = source
        self._fallback = fallback
        self._refresh_every = refresh_every
        self._clock = clock
        self._last_good: MasterData | None = None
        self._fetched_at: datetime | None = None

    def get(self) -> MasterData:
        now = self._clock()
        if (
            self._last_good is not None
            and self._fetched_at is not None
            and now - self._fetched_at < self._refresh_every
        ):
            return self._last_good
        try:
            data = self.source.fetch()
        except Exception as exc:  # any source failure keeps the last good copy
            if self._last_good is None and self._fallback is None:
                raise
            logger.warning("master data refresh from %s failed: %s", self.source.name, exc)
            if self._last_good is None and self._fallback is not None:
                self._last_good = self._fallback.fetch()
            self._fetched_at = now  # retry at the next refresh, not on every call
            assert self._last_good is not None
            return self._last_good
        self._last_good = data
        self._fetched_at = now
        return data


def _build_cache(kind: Literal["seed", "cenomi"]) -> CachedMasterData:
    if kind == "cenomi":
        return CachedMasterData(CenomiMasterDataSource(), fallback=SeedMasterDataSource())
    return CachedMasterData(SeedMasterDataSource())


_cache = _build_cache("seed")


def configure_master_data(kind: Literal["seed", "cenomi"]) -> None:
    """Choose the master data source (MASTER_DATA_SOURCE); create_app calls this once."""
    global _cache
    if _cache.source.name != kind:
        _cache = _build_cache(kind)


def load_master_data() -> MasterData:
    """The current master data from the configured source."""
    return _cache.get()
